def load(p):
    try:
        return json.load(open(p, encoding="utf-8"))
    except (OSError, ValueError):
        return None


def isnum(x):
    return isinstance(x, (int, float)) and not isinstance(x, bool) and x == x


def f(x, d=3):
    return f"{x:.{d}f}" if isnum(x) else "--"


def ci(x, d=2):
    return f"[{x[0]:.{d}f}, {x[1]:.{d}f}]" if isinstance(x, (list, tuple)) and len(x) == 2 and all(isnum(v) for v in x) else "--"


def md_name(s):
    return s.replace("$M>\\tau$", "M>tau").replace("$>\\tau$", ">tau").replace("$M$", "M").replace("$", "")


def tex_esc(s):
    return s.replace("_", "\\_").replace("%", "\\%").replace("&", "\\&").replace("#", "\\#")


def md_table(head, rows):
    return ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(map(str, r)) + " |" for r in rows]


def tex_table(name, caption, head, rows, note=None):
    """booktabs table -> results/latex/<name>.tex (cells are already TeX-safe)"""
    TEX.mkdir(parents=True, exist_ok=True)
    L = ["% auto-generated by neutralens.aggregate -- do not edit", "\\begin{table}[t]", "\\centering", "\\small",
         f"\\caption{{{caption}}}", f"\\label{{tab:{name}}}", "\\resizebox{\\linewidth}{!}{%",
         "\\begin{tabular}{l" + "c" * (len(head) - 1) + "}", "\\toprule", " & ".join(head) + " \\\\", "\\midrule"]
    L += [" & ".join(str(c).replace("[", "{[}").replace("]", "{]}") if i else str(c) for i, c in enumerate(r)) + " \\\\"
          for r in rows] or ["\\multicolumn{" + str(len(head)) + "}{c}{(not yet available)} \\\\"]
    L += ["\\bottomrule", "\\end{tabular}}"]
    if note:
        L.append(f"\\\\[2pt]\\footnotesize {note}")
    L.append("\\end{table}")
    (TEX / f"{name}.tex").write_text("\n".join(L) + "\n", encoding="utf-8")


