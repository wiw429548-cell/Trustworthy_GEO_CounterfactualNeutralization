            fig, ax = plt.subplots(figsize=(5, 2.8))
            dfs = ["none", "neutralens_exact", "neutralens_amortised", "neutral_all"]
            for i, dname in enumerate(dfs):
                ax.bar(np.arange(len(fams)) + i * 0.2, [ad[k][dname]["ASR"] or 0 for k in fams], 0.2, label=dname)
            ax.set_xticks(np.arange(len(fams)) + 0.3)
            ax.set_xticklabels(fams, rotation=20, fontsize=7)
            ax.set_ylabel("ASR")
            ax.legend(fontsize=6)
            save(fig, "adaptive")


