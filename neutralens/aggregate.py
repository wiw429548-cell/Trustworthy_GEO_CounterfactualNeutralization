    brows = []
    for k in [k for k in BL_ORDER if k in bd] + [k for k in bd if k not in BL_ORDER]:
        v = bd[k]
        p = bp.get(k) or {}
        brows.append([DEF_NAMES.get(k, tex_esc(k)), f(v.get("ASR_manipulative")), ci(v.get("ASR_manipulative_ci")),
                      f(v.get("ASR_geo")), f(v.get("legit_gain_retention"), 2), f(v.get("benign_quality"), 2),
                      _dq(v.get("benign_quality_delta_vs_none")), f(v.get("legit_quality"), 2),
                      (f"{p['delta_ASR']:+.3f} ($p$={p['p_mcnemar']:.1e})" if p else "--")])
    if brows:
        L += [f"## Literature defences vs NeutraLens (main engine, same {bs.get('n_queries')} test queries)", ""]
        L += md_table(["defence", "ASR manip.", "95% CI", "ASR GEO", "legit gain kept", "Q clean", "dQ clean [CI]",
                       "Q legit", "NeutraLens - this (McNemar p)"], [[md_name(r[0])] + r[1:] for r in brows]) + [""]
    else:
        missing.append(f"data/engine/{slug(main_e)}/gens_baselines.jsonl (literature baselines)")
